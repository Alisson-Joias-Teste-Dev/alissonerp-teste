-- Movimentacao Interna / Solicitacao de Peca — MULTIPLAS FOTOS + OBS na devolucao
--
-- O QUE FAZ:
--   1. Cria a tabela filha solicitacao_peca_fotos (uma linha por foto), pra que
--      cada passo fisico (entrega, recebimento, devolucao) aceite VARIAS fotos
--      em vez de uma so.
--   2. Copia as fotos que ja existem (colunas foto_entrega/foto_recebimento/
--      foto_devolucao) pra tabela nova, preservando quem tirou e quando.
--   3. Adiciona obs_devolucao na solicitacoes_peca — observacao opcional que o
--      estoque escreve ao confirmar o recebimento da peca de volta.
--
-- O PORQUE (regra de negocio): os usuarios pediram poder anexar mais de uma foto
-- por passo (varios angulos da peca, nota, etc.) e um espaco pra o estoque anotar
-- o estado da peca na volta ("voltou com risco perto do fecho"). Uma coluna de
-- texto unica (foto_*) so guarda um caminho; por isso a tabela filha.
--
-- MODELO: as colunas antigas foto_entrega/foto_recebimento/foto_devolucao ficam
-- CONGELADAS (nao removidas — Database Safety). A partir daqui a fonte de verdade
-- das fotos e a tabela solicitacao_peca_fotos; as colunas antigas so servem de
-- backup do que ja tinha (e ja foram copiadas pra ca). A leitura da tela agrega
-- da tabela nova.
--
-- IMPACTO SE ALTERADO/REMOVIDO: sem a tabela, o passo com foto na API quebra ao
-- inserir. Sem obs_devolucao, o UPDATE da confirmacao de devolucao falha (42703).
--
-- NAO MOVIMENTA ESTOQUE: continua valendo — este modulo so registra posse.

BEGIN;

-- 1) Tabela filha: uma linha por foto de cada passo.
CREATE TABLE IF NOT EXISTS alissonerp.solicitacao_peca_fotos (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  solicitacao_id BIGINT NOT NULL REFERENCES alissonerp.solicitacoes_peca(id) ON DELETE CASCADE,
  etapa          VARCHAR(20) NOT NULL,          -- entrega | recebimento | devolucao
  foto_path      TEXT NOT NULL,                 -- caminho no bucket protocolo-fotos
  criado_por_id  UUID,                          -- quem anexou (herda do passo na migracao)
  criado_em      TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT chk_solic_foto_etapa CHECK (etapa IN ('entrega','recebimento','devolucao'))
);

CREATE INDEX IF NOT EXISTS idx_solic_foto_solic ON alissonerp.solicitacao_peca_fotos (solicitacao_id);
CREATE INDEX IF NOT EXISTS idx_solic_foto_etapa ON alissonerp.solicitacao_peca_fotos (solicitacao_id, etapa);

-- 2) Copia as fotos ja existentes (idempotente: NOT EXISTS por par solicitacao+etapa).
--    Herda quem/quando do passo correspondente. Devolucao usa finalizado_* (foi
--    quem confirmou a volta com foto).
INSERT INTO alissonerp.solicitacao_peca_fotos (solicitacao_id, etapa, foto_path, criado_por_id, criado_em)
SELECT s.id, 'entrega', s.foto_entrega, s.entregue_por_id, COALESCE(s.entregue_em, s.created_at)
FROM alissonerp.solicitacoes_peca s
WHERE s.foto_entrega IS NOT NULL AND btrim(s.foto_entrega) <> ''
  AND NOT EXISTS (
    SELECT 1 FROM alissonerp.solicitacao_peca_fotos f
    WHERE f.solicitacao_id = s.id AND f.etapa = 'entrega' AND f.foto_path = s.foto_entrega
  );

INSERT INTO alissonerp.solicitacao_peca_fotos (solicitacao_id, etapa, foto_path, criado_por_id, criado_em)
SELECT s.id, 'recebimento', s.foto_recebimento, s.recebido_por_id, COALESCE(s.recebido_em, s.created_at)
FROM alissonerp.solicitacoes_peca s
WHERE s.foto_recebimento IS NOT NULL AND btrim(s.foto_recebimento) <> ''
  AND NOT EXISTS (
    SELECT 1 FROM alissonerp.solicitacao_peca_fotos f
    WHERE f.solicitacao_id = s.id AND f.etapa = 'recebimento' AND f.foto_path = s.foto_recebimento
  );

INSERT INTO alissonerp.solicitacao_peca_fotos (solicitacao_id, etapa, foto_path, criado_por_id, criado_em)
SELECT s.id, 'devolucao', s.foto_devolucao, s.finalizado_por_id, COALESCE(s.finalizado_em, s.created_at)
FROM alissonerp.solicitacoes_peca s
WHERE s.foto_devolucao IS NOT NULL AND btrim(s.foto_devolucao) <> ''
  AND NOT EXISTS (
    SELECT 1 FROM alissonerp.solicitacao_peca_fotos f
    WHERE f.solicitacao_id = s.id AND f.etapa = 'devolucao' AND f.foto_path = s.foto_devolucao
  );

-- 3) Observacao do estoque ao confirmar a devolucao (opcional).
ALTER TABLE alissonerp.solicitacoes_peca
  ADD COLUMN IF NOT EXISTS obs_devolucao TEXT;

COMMIT;
