-- Vídeo opcional por treinamento (Central de Treinamentos).
-- Só o desenvolvedor anexa (trava de role na API). Guarda 1 vídeo por
-- treinamento (chave), no bucket público treinamento-videos (streaming nativo,
-- igual ordem-videos/vendas-videos). Vídeo de treinamento não é sensível.

CREATE TABLE IF NOT EXISTS alissonerp.treinamento_videos (
  id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  treinamento_key VARCHAR(80) NOT NULL UNIQUE,   -- ex.: 'movimentacao-interna'
  video_path      TEXT NOT NULL,                 -- path no bucket treinamento-videos
  updated_by      UUID,
  updated_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Bucket público de vídeos de treinamento (espelha ordem-videos/vendas-videos).
INSERT INTO storage.buckets (id, name, public)
VALUES ('treinamento-videos', 'treinamento-videos', true)
ON CONFLICT (id) DO NOTHING;
