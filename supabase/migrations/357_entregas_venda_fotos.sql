-- Migration 357: multiplas fotos na confirmacao de entrega (avulsa e de pedido)
-- ⚠️ MIGRATION CRIADA COMO ARQUIVO — NAO EXECUTADA. Rodar so depois de revisao/aprovacao.
--
-- O QUE FAZ:
--   Cria a tabela filha alissonerp.entregas_venda_fotos (uma linha por foto),
--   pra que a confirmacao de UMA entrega (avulsa OU de pedido) aceite VARIAS
--   fotos em vez de uma so.
--
-- O PORQUE (decisao Jonathan, 21/07): "sempre que o motoboy tiver uma corrida
-- ele pode anexar fotos antes de finalizar — nao e obrigatorio". A coluna
-- atual entregas_venda.foto_entrega_path (migration 287) so guarda UM
-- caminho; por isso a tabela filha — MESMO PADRAO ja usado no modulo
-- Movimentacao Interna / Solicitacao de Peca (tabela
-- alissonerp.solicitacao_peca_fotos, migration 349): tabela normalizada,
-- 1 linha por foto, permite metadados por foto (quem tirou, quando).
--
-- POR QUE NAO ETAPA (diferenca vs. solicitacao_peca_fotos): la existem 3
-- momentos fisicos por solicitacao (entrega/recebimento/devolucao), aqui so
-- existe UM momento por entrega (a confirmacao — codigo A/B na entrega de
-- pedido, ou botao simples na avulsa). Sem coluna etapa: seria sempre a
-- mesma constante, poluicao sem beneficio.
--
-- MODELO: a coluna antiga foto_entrega_path fica CONGELADA (nao removida —
-- Database Safety, e nao e mais escrita pelo codigo novo) — continua valida
-- pra ler os registros ANTIGOS (antes desta migration). A fonte de verdade
-- das fotos NOVAS passa a ser esta tabela. A leitura unifica as duas fontes
-- num helper unico (buscarFotosEntrega, src/lib/entrega-venda.ts): se existir
-- QUALQUER linha na tabela filha pra aquela entrega, ela manda; senao cai no
-- fallback da coluna antiga (mesmo padrao de leitura do modulo Movimentacao
-- Interna, ver src/app/(dashboard)/movimentacao-interna/page.tsx).
--
-- SEM COPIA DE DADOS HISTORICOS (diferenca vs. migration 349): o pagamento do
-- motoboy foi acertado ate 19/07 e recomeca do zero (decisao Jonathan) — nao
-- ha necessidade de "migrar" fotos antigas pra tabela nova pra efeito de
-- acerto financeiro. O fallback de leitura (acima) ja cobre exibir fotos
-- antigas sem precisar duplicar o dado fisicamente.
--
-- IMPACTO SE ALTERADO/REMOVIDO: sem a tabela, a confirmacao com fotos falha
-- ao inserir (best-effort — nao derruba a confirmacao, so perde a foto, ver
-- comentario em confirmarEntrega/confirmarFreteAvulso). Sem o helper unico,
-- telas que listam fotos duplicariam a logica de fallback ou esqueceriam dele
-- e fotos antigas sumiriam da tela.
--
-- NAO MOVIMENTA ESTOQUE: fotos sao so comprovante visual (auditoria do
-- relatorio de pagamento do motoboy) — a baixa de estoque continua disparada
-- em baixarEstoqueDaEntrega, sem relacao com esta tabela.

BEGIN;

CREATE TABLE IF NOT EXISTS alissonerp.entregas_venda_fotos (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  entrega_id     BIGINT NOT NULL REFERENCES alissonerp.entregas_venda(id) ON DELETE CASCADE,
  foto_path      TEXT NOT NULL,                 -- caminho no bucket pagamento-fotos
  criado_por_id  UUID,                          -- quem anexou (usuario logado na confirmacao)
  criado_em      TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_entregas_venda_fotos_entrega ON alissonerp.entregas_venda_fotos (entrega_id);

COMMIT;
