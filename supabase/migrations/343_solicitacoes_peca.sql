-- Movimentacao Interna / Solicitacao de Peca (v1)
--
-- Ciclo: solicitado -> entregue -> recebido -> [ cliente_levou => finalizado ]
--                                            \-> volta_solicitada -> finalizado (devolvido)
-- Registra quem esta com a peca dentro da loja: consultora solicita, estoque
-- entrega, solicitante confirma recebimento, e resolve — cliente levou (encerra
-- na hora) ou devolucao ao estoque (solicitante pede a volta, estoque confirma
-- o recebimento de volta com foto, ai encerra). Sem PCP, sem aprovacao, sem role
-- propria — qualquer usuario autenticado opera; grava quem fez cada passo + data.
--
-- Independente do modulo Protocolo (que e transporte Loja<->Fabrica com motoboy).

-- Remove a tabela do experimento anterior (reaproveitava protocolos; abandonado).
-- Estava vazia em producao; em homolog so tinha dado de teste.
DROP TABLE IF EXISTS alissonerp.protocolo_produtos;

CREATE TABLE IF NOT EXISTS alissonerp.solicitacoes_peca (
  id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  status            VARCHAR(20) NOT NULL DEFAULT 'solicitado',
  descricao         TEXT,                          -- texto livre p/ lote ("todos os aneis da vitrine 3")
  -- passo 1: solicitacao (consultora pede)
  solicitante_id    UUID,
  created_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
  -- passo 2: entrega (estoque separa e entrega) — foto obrigatoria
  entregue_por_id   UUID,
  entregue_em       TIMESTAMPTZ,
  foto_entrega      TEXT,
  -- passo 3: recebimento (solicitante confirma) — foto obrigatoria
  recebido_por_id   UUID,
  recebido_em       TIMESTAMPTZ,
  foto_recebimento  TEXT,
  -- passo 4b (opcional): solicitante pede a volta ao estoque — sem foto
  volta_solicitada_por_id UUID,
  volta_solicitada_em     TIMESTAMPTZ,
  -- passo final: cliente_levou (a partir de recebido) OU devolvido (estoque
  -- confirma a volta, com foto em foto_devolucao)
  finalizado_por_id UUID,
  finalizado_em     TIMESTAMPTZ,
  motivo_final      VARCHAR(20),                   -- devolvido | cliente_levou
  foto_devolucao    TEXT,                          -- foto do estoque ao confirmar a devolucao
  updated_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT chk_solic_peca_status CHECK (status IN ('solicitado','entregue','recebido','volta_solicitada','finalizado')),
  CONSTRAINT chk_solic_peca_motivo CHECK (motivo_final IS NULL OR motivo_final IN ('devolvido','cliente_levou'))
);

CREATE INDEX IF NOT EXISTS idx_solic_peca_status      ON alissonerp.solicitacoes_peca (status);
CREATE INDEX IF NOT EXISTS idx_solic_peca_solicitante ON alissonerp.solicitacoes_peca (solicitante_id);
CREATE INDEX IF NOT EXISTS idx_solic_peca_created     ON alissonerp.solicitacoes_peca (created_at DESC);

CREATE TABLE IF NOT EXISTS alissonerp.solicitacao_peca_produtos (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  solicitacao_id BIGINT NOT NULL REFERENCES alissonerp.solicitacoes_peca(id) ON DELETE CASCADE,
  produto_id     BIGINT REFERENCES public.produtos(id_produto) ON DELETE SET NULL,
  created_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (solicitacao_id, produto_id)
);

CREATE INDEX IF NOT EXISTS idx_solic_peca_prod_solic   ON alissonerp.solicitacao_peca_produtos (solicitacao_id);
CREATE INDEX IF NOT EXISTS idx_solic_peca_prod_produto ON alissonerp.solicitacao_peca_produtos (produto_id);
